#!/usr/bin/env python3
"""
Generate ``THIRD-PARTY-LICENSES.md`` for the dependencies bundled with ``oscal``.

The authoritative way to run this is in an environment where ONLY ``oscal``'s runtime
closure is installed — e.g. a fresh virtualenv after ``pip install dist/oscal-*.whl`` —
so that every installed distribution except ``oscal`` itself is, by construction, a
bundled runtime dependency. The release workflow does exactly that.

For ad-hoc/local use in a mixed environment you may pass an explicit list of distribution
names to restrict the report to a known closure, e.g.::

    python scripts/generate_thirdparty_licenses.py \
        jsonpath-python xmlschema elementpath PyYAML markdown \
        requests urllib3 certifi charset-normalizer idna packaging
"""
from __future__ import annotations

import argparse
from importlib import metadata
from pathlib import Path

SELF = "oscal"

# Build/test tooling that must never appear in a RUNTIME license manifest, in case the
# script is run in a non-clean environment (ignored when an explicit list is given).
DEV_BLOCKLIST = {
    "pip", "setuptools", "wheel", "build", "twine",
    "pytest", "pytest-cov", "pytest-asyncio", "hypothesis", "coverage",
    "ruff", "cyclonedx-bom", "pip-licenses", "prettytable", "pluggy", "iniconfig",
}


def _canon(name: str) -> str:
    return name.lower().replace("_", "-")


def _license_id(dist: metadata.Distribution) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip()
                   for c in md.get_all("Classifier", []) or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(dict.fromkeys(classifiers))
    lic = md.get("License")
    if lic and "\n" not in lic and len(lic) < 80:
        return lic
    return "(see bundled license text)"


def _homepage(dist: metadata.Distribution) -> str:
    md = dist.metadata
    if md.get("Home-page"):
        return md["Home-page"]
    for entry in md.get_all("Project-URL", []) or []:
        label, _, link = entry.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "repository", "source code"):
            return link.strip()
    return ""


def _license_texts(dist: metadata.Distribution) -> list[tuple[str, str]]:
    """Return (filename, text) for every license/notice file shipped in the dist-info."""
    out: list[tuple[str, str]] = []
    base = getattr(dist, "_path", None)
    if not (base and Path(base).is_dir()):
        return out
    base = Path(base)
    seen = set()
    patterns = ["licenses/**/*", "LICENSE*", "COPYING*", "NOTICE*", "AUTHORS*"]
    for pat in patterns:
        for path in sorted(base.glob(pat)):
            if path.is_file() and path not in seen:
                seen.add(path)
                try:
                    out.append((path.name, path.read_text(encoding="utf-8", errors="replace").strip()))
                except OSError:
                    pass
    return out


def _target_dists(explicit: list[str]) -> list[metadata.Distribution]:
    if explicit:
        wanted = {_canon(n) for n in explicit}
        dists = [d for d in metadata.distributions() if _canon(d.metadata["Name"]) in wanted]
    else:
        dists = [d for d in metadata.distributions()
                 if _canon(d.metadata["Name"]) not in DEV_BLOCKLIST
                 and _canon(d.metadata["Name"]) != SELF]
    # De-duplicate (a path can expose the same dist twice) and sort by name.
    by_name: dict[str, metadata.Distribution] = {}
    for d in dists:
        by_name.setdefault(_canon(d.metadata["Name"]), d)
    return [by_name[k] for k in sorted(by_name)]


def build_markdown(dists: list[metadata.Distribution]) -> str:
    lines: list[str] = []
    lines.append("# Third-Party Licenses")
    lines.append("")
    lines.append("`oscal` is distributed under the MIT License. When `oscal` is bundled into a larger")
    lines.append("distribution (e.g. CyberCraft), the following third-party components are redistributed")
    lines.append("with it. Their copyright and license notices are reproduced below in satisfaction of")
    lines.append("those licenses' attribution requirements.")
    lines.append("")
    lines.append("> This file is generated by `scripts/generate_thirdparty_licenses.py` from the")
    lines.append("> installed runtime closure. Do not edit by hand — regenerate it (the release")
    lines.append("> workflow does so against the built wheel). The machine-readable equivalent is the")
    lines.append("> CycloneDX SBOM attached to each GitHub Release.")
    lines.append("")

    lines.append("## Bundled distributions")
    lines.append("")
    lines.append("| Component | Version | License |")
    lines.append("|---|---|---|")
    for d in dists:
        lines.append(f"| {d.metadata['Name']} | {d.version} | {_license_id(d)} |")
    lines.append("")

    for d in dists:
        name = d.metadata["Name"]
        lines.append(f"### {name} {d.version}")
        lines.append("")
        lines.append(f"- License: {_license_id(d)}")
        hp = _homepage(d)
        if hp:
            lines.append(f"- Homepage: {hp}")
        lines.append("")
        texts = _license_texts(d)
        if texts:
            for fname, text in texts:
                lines.append(f"<details><summary>{name} — {fname}</summary>")
                lines.append("")
                lines.append("```")
                lines.append(text)
                lines.append("```")
                lines.append("")
                lines.append("</details>")
                lines.append("")
        else:
            lines.append("_No license file shipped in the distribution metadata; "
                         "see the homepage above for the full text._")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("dists", nargs="*", help="Explicit distribution names (optional).")
    ap.add_argument("--output", "-o", default="THIRD-PARTY-LICENSES.md")
    args = ap.parse_args()

    dists = _target_dists(args.dists)
    if not dists:
        print("No target distributions found.")
        return 1
    Path(args.output).write_text(build_markdown(dists), encoding="utf-8")
    print(f"Wrote {args.output} covering {len(dists)} components:")
    for d in dists:
        print(f"  - {d.metadata['Name']} {d.version} ({_license_id(d)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
